    _user("5", [_result("t2", "b = 2")]),
    _user("6", [_result("t1", "a = 1")], toolUseResult={"type": "text", "file": {"filePath": f"{CWD}/a.py"}}),
    _assistant("7", [_tool("t3", "Bash", {"command": "pytest -q"})]),
    _user("8", [_result("t3", "1 failed", is_error=True)], toolUseResult="Error: 1 failed"),
